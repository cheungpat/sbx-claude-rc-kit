#!/usr/bin/env bash
# Regenerate claude-rc/spec.yaml from Docker's official claude kit.
# The only changes made: the kit is renamed to claude-rc and its top-level
# `credentials:` block (Anthropic credential injection) is removed, so the
# sbx proxy stops rewriting Authorization on api.anthropic.com and Claude Code
# Remote Control (including server mode) can authenticate with its own tokens.
set -euo pipefail

UPSTREAM_REPO="${UPSTREAM_REPO:-https://github.com/docker/sbx-kits-contrib.git}"
UPSTREAM_REF="${UPSTREAM_REF:-main}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

git clone -q --depth 1 --branch "$UPSTREAM_REF" "$UPSTREAM_REPO" "$TMP/upstream"
SHA="$(git -C "$TMP/upstream" rev-parse HEAD)"
SRC="$TMP/upstream/claude/spec.yaml"

grep -q '^credentials:' "$SRC" || { echo "upstream spec has no top-level credentials: block — review manually" >&2; exit 1; }
grep -q '^name: claude$' "$SRC" || { echo "upstream spec name is not 'claude' — review manually" >&2; exit 1; }

{
  echo "# GENERATED by scripts/sync-upstream.sh — do not edit by hand."
  echo "# Source: $UPSTREAM_REPO claude/spec.yaml @ $SHA"
  echo "# Changes: name/displayName/description changed; top-level credentials: block removed."
  awk '
    /^credentials:/ { skip=1; next }
    skip && /^[A-Za-z]/ { skip=0 }
    !skip
  ' "$SRC" | sed -e 's/^name: claude$/name: claude-rc/' \
        -e 's/^displayName: .*/displayName: Claude Code (Remote Control compatible)/' \
        -e 's/^description: .*/description: Docker'"'"'s claude kit without Anthropic credential injection, so Remote Control (incl. server mode) can authenticate. Sign in with \/login inside the sandbox./'
} > "$ROOT/claude-rc/spec.yaml"

if grep -q '^credentials:' "$ROOT/claude-rc/spec.yaml"; then
  echo "credentials block still present — aborting" >&2; exit 1
fi
echo "$SHA" > "$ROOT/claude-rc/UPSTREAM_SHA"
echo "Synced from $SHA"
